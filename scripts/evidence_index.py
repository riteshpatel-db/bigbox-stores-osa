"""Write evidence/INDEX.md: one row per evidence file, read from the file's own header.

  uv run python scripts/evidence_index.py

Stage, run timestamp, UC objects and size come from each file; the claim column is the one-line
summary below (no numbers, so it can't go stale: the numbers live in the files). Totals are checked
against the limits in check_evidence.py.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from check_evidence import MAX_CHARS, MAX_FILES, MAX_TOTAL  # noqa: E402

EVIDENCE = ROOT / "evidence"
CLAIMS = {
    "00_raw_data.md": "The seeded generator wrote the raw extracts, defects and ground truth; it is deterministic",
    "00b_live_drip.md": "The live window is released in micro-batches that Auto Loader picks up",
    "01_lakeflow.md": "The pipeline's expectations catch every injected defect type; gold reproduces the ground truth",
    "02_unity_catalog.md": "Personas, grants, row filter and PII mask, proven by querying as each service principal; metric views equal hand SQL",
    "02b_catalog_metadata.md": "Comments, governed tags and lineage across the catalog",
    "03_ml.md": "Features, the six-candidate sweep on one holdout, registry aliases, batch scoring, recommendations, endpoint parity",
    "03b_backtest_value.md": "The ML policy against the incumbent on the same demand, and the value model with its sensitivity",
    "04_lakebase.md": "Synced table parity and latency, decisions round-tripped from Postgres to Delta",
    "05_genie.md": "Genie answers the benchmark questions against reference SQL in three runs; ablation without curation",
    "06_app.md": "The deployed app, its bindings and least privilege, a real session and the HTTP smoke test",
    "07_cost.md": "What the build cost, unit costs, the monthly run cost and the ROI",
}


def field(text: str, name: str) -> str:
    m = re.search(rf"^- {name}: (.*)$", text, re.M)
    return m.group(1).strip() if m else "-"


def main() -> int:
    files = sorted(p for p in EVIDENCE.glob("[0-9]*.md"))
    rows, total = [], 0
    for f in files:
        text = f.read_text()
        total += len(text)
        title = text.splitlines()[0].lstrip("# ").strip()
        stage = title.split(" ", 1)[0]
        objs = field(text, "UC objects")
        n_objs = objs.count("`") // 2
        run = field(text, "Run at")
        run = run.replace(" (UTC)", "").split("; evidence")[0]
        rows.append(
            f"| {stage} | [{f.name}]({f.name}) | {CLAIMS.get(f.name, title)} | {n_objs} | {run} | {len(text):,} |"
        )
    md = [
        "# Evidence index",
        "",
        "Each file is text copied from real runs (header: command, run time, workspace, UC objects, source). "
        "Generated by `scripts/evidence_index.py`; limits checked by `scripts/check_evidence.py`.",
        "",
        "| stage | file | claim proven | UC objects | run at (UTC) | chars |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        f"Totals: {len(files)} evidence files (limit {MAX_FILES}, this index included: {len(files) + 1}); "
        f"largest {max(len(f.read_text()) for f in files):,} chars (limit {MAX_CHARS:,}); "
        f"{total:,} chars in total (limit {MAX_TOTAL:,}, before this index).",
    ]
    (EVIDENCE / "INDEX.md").write_text("\n".join(md) + "\n")
    print(f"wrote evidence/INDEX.md ({len(files)} files, {total:,} chars)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
